import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Extractor, ExtractorConfig, ExtractorLogLevel } from '@microsoft/api-extractor';

const root = join(import.meta.dirname, '..');
const reportFolder = join(root, 'api');
const update = process.argv.includes('--update');
const temp = mkdtempSync(join(tmpdir(), 'formhaus-api-'));
mkdirSync(reportFolder, { recursive: true });

const ENTRIES = {
  core: ['index', 'cloud', 'server', 'i18n', 'fix', 'research', 'schema', 'fields', 'controls'],
  react: ['index', 'cloud', 'controls', 'i18n'],
  vue: ['index', 'cloud', 'controls', 'i18n'],
};

const SILENT = { logLevel: ExtractorLogLevel.None };

const failures = [];

for (const [pkg, entries] of Object.entries(ENTRIES)) {
  const projectFolder = join(root, 'packages', pkg);
  for (const entry of entries) {
    const name = entry === 'index' ? pkg : `${pkg}-${entry}`;
    const mainEntryPointFilePath = join(projectFolder, 'dist', `${entry}.d.ts`);
    if (!existsSync(mainEntryPointFilePath)) {
      failures.push(`${name}: ${mainEntryPointFilePath} is missing; run pnpm build first`);
      continue;
    }
    const config = ExtractorConfig.prepare({
      configObject: {
        projectFolder,
        mainEntryPointFilePath,
        compiler: {
          overrideTsconfig: {
            compilerOptions: {
              target: 'ES2022',
              module: 'ESNext',
              moduleResolution: 'Bundler',
              lib: ['ES2022', 'DOM', 'DOM.Iterable'],
              types: [],
              strict: true,
              skipLibCheck: true,
            },
            files: [mainEntryPointFilePath],
          },
        },
        apiReport: {
          enabled: true,
          reportFileName: `${name}.api.md`,
          reportFolder,
          reportTempFolder: temp,
        },
        docModel: { enabled: false },
        dtsRollup: { enabled: false },
        tsdocMetadata: { enabled: false },
        messages: {
          compilerMessageReporting: { default: SILENT },
          extractorMessageReporting: { default: SILENT },
          tsdocMessageReporting: { default: SILENT },
        },
      },
      configObjectFullPath: undefined,
      packageJsonFullPath: join(projectFolder, 'package.json'),
    });
    const errors = [];
    const result = Extractor.invoke(config, {
      localBuild: update,
      messageCallback: (message) => {
        if (message.logLevel === ExtractorLogLevel.Error) errors.push(message.text);
        message.handled = true;
      },
    });
    if (result.apiReportChanged && !update) {
      failures.push(`${name}: public API changed`);
      spawnSync('git', ['diff', '--no-index', '--', join(reportFolder, `${name}.api.md`), join(temp, `${name}.api.md`)], {
        stdio: 'inherit',
      });
    } else if (!result.succeeded) {
      failures.push(`${name}: ${errors.join('; ') || 'api-extractor failed'}`);
    } else {
      console.log(`${name}: ${result.apiReportChanged ? 'updated' : 'unchanged'}`);
    }
  }
}

const css = readFileSync(join(root, 'packages/core/style.css'), 'utf8');
const [theming, stable] = readFileSync(join(root, 'docs/guide/index.md'), 'utf8')
  .split('### Optional baseline styles')[1]
  .split('### Stable names');
const documented = theming
  .split('\n')
  .filter((line) => line.startsWith('| `--fh-'))
  .map((line) => line.split('|')[1])
  .join(' ')
  .replace(/`--fh-([a-z-]+)(\d+)` … `--fh-\1(\d+)`/g, (_, base, from, to) =>
    Array.from({ length: Number(to) - Number(from) + 1 }, (_, index) => `\`--fh-${base}${Number(from) + index}\``).join(' '),
  );
const properties = [...new Set(documented.match(/--fh-[a-z0-9-]+/g))].sort();
const used = new Set(css.match(/--fh-[a-z0-9-]+/g));
for (const name of properties) if (!used.has(name)) failures.push(`style: ${name} is documented but missing from style.css`);
for (const name of used)
  if (!properties.includes(name))
    failures.push(`style: ${name} is in style.css but not in the theming docs; document it or rename it to --fhi-*`);
const classes = [...stable.matchAll(/^\| `(fh-[a-z0-9_-]+)` \|/gm)].map(([, name]) => name);
for (const name of classes)
  if (!new RegExp(`\\.${name}(?![\\w-])`).test(css)) failures.push(`style: .${name} is documented but missing from style.css`);
const styleReport = `# Stable style names of @formhaus/core/style.css

Generated by scripts/api-report.mjs from the theming docs. A rename or removal here is a breaking change from 1.0. Custom properties that start with --fhi- are private.

## Custom properties

${properties.map((name) => `- \`${name}\``).join('\n')}

## Classes

${classes.map((name) => `- \`.${name}\``).join('\n')}
`;
const stylePath = join(reportFolder, 'style.api.md');
if (update) {
  writeFileSync(stylePath, styleReport);
  console.log('style: updated');
} else if (!existsSync(stylePath) || readFileSync(stylePath, 'utf8') !== styleReport) {
  failures.push('style: documented --fh-* names or classes changed');
  writeFileSync(join(temp, 'style.api.md'), styleReport);
  spawnSync('git', ['diff', '--no-index', '--', stylePath, join(temp, 'style.api.md')], { stdio: 'inherit' });
} else {
  console.log('style: unchanged');
}

rmSync(temp, { recursive: true, force: true });

if (failures.length > 0) {
  console.error(failures.join('\n'));
  console.error('\nIf the change is intended, run pnpm build && pnpm api:update and commit api/*.api.md.');
  process.exit(1);
}
