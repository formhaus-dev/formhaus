import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTEXTS, cssEntries, DEFAULT_CONTEXT, MIX_SUPPORTS } from '../style-dictionary.config.mjs';
import { loadDictionary, validateTokens } from './tokens-resolver.mjs';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokensDir = resolve(packageRoot, 'tokens');
const stylePath = resolve(packageRoot, 'style.css');
const START = '/* fh-tokens:start, generated by pnpm -C packages/core tokens */';
const END = '/* fh-tokens:end */';

let validation;
try {
  validation = await validateTokens(tokensDir);
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
if (validation.problems.length) {
  console.error(validation.problems.join('\n'));
  process.exit(1);
}
const { resolver } = validation;
const load = (selected) => loadDictionary(resolver.sourcesFor(selected));

const declarations = (entries, value = (entry) => entry.value, name = (entry) => entry.name) => {
  const lines = [];
  let group;
  for (const entry of entries) {
    const declaration = `--${name(entry)}: ${value(entry)};`;
    if (entry.group === group) lines[lines.length - 1] += ` ${declaration}`;
    else lines.push(declaration);
    group = entry.group;
  }
  return lines;
};

const block = (selector, lines, indent = '') =>
  [`${indent}${selector} {`, ...lines.map((line) => (line ? `${indent}  ${line}` : '')), `${indent}}`].join('\n');
const autoName = (entry) => `fhi-auto-${entry.auto}`;

const defaults = cssEntries(await load());
const byName = new Map(defaults.map((entry) => [entry.name, entry]));
const blocks = [
  block(DEFAULT_CONTEXT.base, declarations(defaults.filter((entry) => !entry.auto))),
  block(
    DEFAULT_CONTEXT.auto,
    declarations(
      defaults.filter((entry) => entry.auto),
      undefined,
      autoName,
    ),
  ),
  block(
    DEFAULT_CONTEXT.public,
    declarations(
      defaults.filter((entry) => entry.auto),
      (entry) => `var(--${autoName(entry)})`,
    ),
  ),
];
const mixBlocks = [
  block(
    DEFAULT_CONTEXT.auto,
    declarations(
      defaults.filter((entry) => entry.mix),
      (entry) => entry.mix,
      autoName,
    ),
    '  ',
  ),
];
const mediaBlocks = [];

for (const context of CONTEXTS) {
  const files = resolver.contextFiles(context.modifier, context.context);
  const entries = cssEntries(await load({ [context.modifier]: context.context })).filter((entry) => files.has(entry.token.filePath));
  const base = declarations(entries.filter((entry) => !entry.auto));
  const auto = declarations(
    entries.filter((entry) => entry.auto && entry.value !== byName.get(entry.name).value),
    undefined,
    autoName,
  );
  const mix = declarations(
    entries.filter((entry) => entry.mix && entry.mix !== byName.get(entry.name).mix),
    (entry) => entry.mix,
    autoName,
  );
  const indent = context.media ? '  ' : '';
  const own = [];
  if (base.length || context.declarations) {
    const head = (context.declarations ?? []).map((declaration) => `${declaration};`);
    own.push(block(context.base, head.length && base.length ? [...head, '', ...base] : [...head, ...base], indent));
  }
  if (auto.length) own.push(block(context.auto, auto, indent));
  if (mix.length) {
    if (context.media) throw new Error(`${context.modifier}.${context.context}: color-mix rules inside media queries are not supported`);
    mixBlocks.push(block(context.auto, mix, '  '));
  }
  if (!own.length) continue;
  if (context.media) mediaBlocks.push(`${context.media} {\n${own.join('\n\n')}\n}`);
  else blocks.push(...own);
}

const generated = [START, ...blocks, `${MIX_SUPPORTS} {\n${mixBlocks.join('\n\n')}\n}`, ...mediaBlocks, END].join('\n\n');
const style = await readFile(stylePath, 'utf8');
const start = style.indexOf(START);
const end = style.indexOf(END);
if (start === -1 || end < start) {
  console.error(`style.css needs the ${START} and ${END} markers`);
  process.exit(1);
}
const next = style.slice(0, start) + generated + style.slice(end + END.length);

if (process.argv.includes('--check')) {
  if (next !== style) {
    console.error('style.css is out of date with tokens/*.tokens.json. Run pnpm -C packages/core tokens.');
    process.exit(1);
  }
  console.log('style.css matches tokens/*.tokens.json.');
} else if (next !== style) {
  await writeFile(stylePath, next);
  console.log('Updated the token blocks in style.css.');
} else {
  console.log('style.css is up to date.');
}
